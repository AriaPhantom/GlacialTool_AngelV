void CexampleDlg::OnBnClickedButtonStartall()
{
	HWND hwnds = findMSWindow();
	bool startPendingAutoLogin = false;
	if (hwnds == 0)
	{
		if (GetAutoLogin())
		{
			startPendingAutoLogin = true;
		}
		else
		{
			CString strMessage;
			strMessage.Format(_T("\u627E\u4E0D\u5230\u7A97\u53E3\uFF0C\u4EE3\u7801: %p"), hwnds);
			AfxMessageBox(strMessage, MB_OK | MB_ICONERROR);
			return;
		}
	}

	BOOL started = FALSE;
	if (startPendingAutoLogin)
	{
		started = ThreadStartPendingAutoLogin();
	}
	else
	{
		long hwnd_long = static_cast<long>(reinterpret_cast<LONG_PTR>(hwnds));
		started = ThreadStart(hwnd_long);
	}

	if (!started)
	{
		return;
	}

	if (!startPendingAutoLogin)
	{
		subSoftStart();
		detectionStart();
	}
}

void CexampleDlg::OnBnClickedButtonStopall()
{
	if (m_statusList == NULL)
	{
		return;
	}

	int item_count = m_statusList->rowCount();
	if (item_count == 0)
	{
		Log(_T("没有窗口"));
		return;
	}

	subSoftPause();

	for (int i = 0; i < item_count; ++i)
	{
		QTableWidgetItem* item = m_statusList->item(i, 0);
		if (item == NULL)
		{
			continue;
		}
		long index = (long)item->data(Qt::UserRole).toLongLong();
		ThreadSetExitState(index);
	}

	int mark_index = item_count - 1;
	while (mark_index >= 0)
	{
		QTableWidgetItem* item = m_statusList->item(mark_index, 0);
		if (item == NULL)
		{
			--mark_index;
			continue;
		}

		long index = (long)item->data(Qt::UserRole).toLongLong();
		if (index >= 0 && index < MAX_HWND)
		{
			if (g_info[index].handle != NULL &&
				(g_info[index].thread_state == State_Runing || g_info[index].thread_state == State_Resuming))
			{
				g_info[index].is_pause = TRUE;
				g_info[index].thread_state = State_Pausing;
			}

			long subIndex = index + MAX_HWND;
			if (g_info[subIndex].handle != NULL &&
				(g_info[subIndex].thread_state == State_Runing || g_info[subIndex].thread_state == State_Resuming))
			{
				g_info[subIndex].is_pause = TRUE;
				g_info[subIndex].thread_state = State_Pausing;
			}
		}

		--mark_index;
	}

	// Pre-mark every running slot before the per-window pause loop so "Pause All"
	// doesn't leave the later rows one more chance to inject Enter/confirm keys.
	SPUtils::ReleaseAllKeysFastKeyboardOnlySkipEnter();

	int list_index = item_count - 1;
	while (list_index >= 0)
	{
		QTableWidgetItem* item = m_statusList->item(list_index, 0);
		if (item == NULL)
		{
			--list_index;
			continue;
		}
		long index = (long)item->data(Qt::UserRole).toLongLong();
		ThreadStop(index);
		--list_index;
	}
}

