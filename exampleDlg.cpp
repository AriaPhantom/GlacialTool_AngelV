void CexampleDlg::SaveAutoLoginPreset(int presetIndex)
{
    CWinApp* app = AfxGetApp();
    if (app == NULL || autoLoginKeys == NULL || autoLoginDelay == NULL)
    {
        return;
    }

    QString keyText = autoLoginKeys->text().trimmed();
    CString keys = CString(keyText.toLocal8Bit().constData());
    bool ok = false;
    int delay = autoLoginDelay->text().trimmed().toInt(&ok);
    if (!ok)
    {
        delay = 200;
    }
    if (delay < 0) delay = 0;
    if (delay > 5000) delay = 5000;

    CString keyName;
    CString delayName;
    if (presetIndex <= 0)
    {
        keyName = _T("AutoLoginKeys");
        delayName = _T("AutoLoginDelay");
    }
    else
    {
        keyName.Format(_T("AutoLoginPreset%dKeys"), presetIndex);
        delayName.Format(_T("AutoLoginPreset%dDelay"), presetIndex);
    }

    app->WriteProfileString(kUiStateSection, keyName, keys);
    app->WriteProfileInt(kUiStateSection, delayName, delay);
}

